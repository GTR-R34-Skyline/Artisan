export const VENDOR_ONBOARDING_FIELD_KEYS = [
  'name',
  'location',
  'craft',
  'experienceYears',
  'story',
] as const;

const FIELD_TRANSLATION_KEY: Record<string, keyof TranslationDict> = {
  name: 'onboarding.field.name',
  email: 'onboarding.field.email',
  phone: 'onboarding.field.phone',
  location: 'onboarding.field.location',
  craft: 'onboarding.field.craft',
  experienceYears: 'onboarding.field.experienceYears',
  story: 'onboarding.field.story',
};

export const getOnboardingFieldLabel = (
  language: SupportedLanguageCode,
  field: string,
): string => {
  const key = FIELD_TRANSLATION_KEY[field];
  if (!key) return field;
  return TRANSLATIONS[language][key] || TRANSLATIONS.en[key] || field;
};

/** Builds the upfront onboarding brief listing the exact required seller parameters. */
export const buildOnboardingRequirementsMessage = (
  language: SupportedLanguageCode,
  fields: readonly string[],
): string => {
  const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
  const lines = fields.map((field, index) => `${index + 1}. ${getOnboardingFieldLabel(language, field)}`);
  return [
    dict['onboarding.intro.title'],
    ...lines,
    '',
    dict['onboarding.intro.body'],
    dict['onboarding.intro.oneShot'],
  ].join('\n');
};
